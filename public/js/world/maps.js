// ---- more layouts ----------------------------------------------------------------------------------------------------
// The extra maps below reuse the five themes above (tracks differ, looks don't). Sunset's theme pins its scenery to a fixed
// box around the original layout, so layouts that borrow it drop those boxes and let the scenery follow the track bounds.
function retheme(theme) {
  const t = structuredClone(theme);
  if (t.buildings) { delete t.buildings.area; delete t.buildings.center; }
  if (t.trees) delete t.trees.area;
  if (t.mountains) delete t.mountains.center;
  return t;
}

